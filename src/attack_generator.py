_PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DATASET_PATH = _PROJECT_ROOT / "data" / "attacks" / "attack_dataset.json"

# Every attack sample gets this appended to expected_slip_layers
# structurally — see module docstring.
_STRUCTURAL_SLIP_LAYERS = ["defensive_tokens"]


# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------

@dataclass
class AttackSample:
    attack_id: str
    category: str                       # direct_injection / indirect_injection / escalation / encoding_obfuscation / benign
    attack_type: str
    raw_attack: str                     # the injection payload itself ("" for benign)
    wrapped_attack: str                 # the payload embedded in a realistic power-grid document
    clean_counterpart: Optional[str] = None
    expected_blocked_by: list = field(default_factory=list)
    expected_slip_layers: list = field(default_factory=list)
    difficulty: str = "medium"             # easy / medium / hard / n/a (benign)
    ground_truth_risk: str = "HIGH"      # LOW / MEDIUM / HIGH / CRITICAL
    image_path: Optional[str] = None    # set only for multimodal samples; None for all text-only samples
    doc_type: str = "unknown"

    def to_dict(self) -> dict:
        return asdict(self)


def _attack(
    attack_id, category, attack_type, raw_attack, wrapped_attack,
    expected_blocked_by, difficulty, ground_truth_risk,
    extra_slip_layers=None,
) -> AttackSample:
    """Helper: builds an AttackSample and appends the structural
    defensive_tokens slip-layer entry automatically (see module
    docstring), plus any sample-specific extra slip layers."""
    slip = list(_STRUCTURAL_SLIP_LAYERS)
    if extra_slip_layers:
        for layer in extra_slip_layers:
            if layer not in slip:
                slip.append(layer)
    return AttackSample(
        attack_id=attack_id,
        category=category,
        attack_type=attack_type,
        raw_attack=raw_attack,
        wrapped_attack=wrapped_attack.strip(),
        expected_blocked_by=expected_blocked_by,
        expected_slip_layers=slip,
        difficulty=difficulty,
        ground_truth_risk=ground_truth_risk,
    )


