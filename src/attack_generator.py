"""
attack_generator.py

Generates the synthetic attack dataset used to evaluate the defense stack
(defense/filtering.py, defensive_tokens.py, zedd.py, rag_memory.py,
human_loop.py) against grid_agent.py.

WHY EVERY ATTACK IS EMBEDDED, NOT BARE
-----------------------------------------
A bare injection string ("Ignore previous instructions...") tells you
almost nothing interesting: Layer 1's pattern matching catches it
trivially, and the evaluation ends there. Every attack in this dataset is
instead embedded inside a realistic power-grid document — a sensor log,
maintenance report, SCADA alert, technician note, or dissolved gas
analysis — because that is what these layers will actually see in
practice, and because realistic embedding is what makes the "hard"
difficulty tier mean anything.

A CRITICAL METHODOLOGICAL POINT: LABELS ARE NOT DERIVED FROM THE DEFENSE CODE
----------------------------------------------------------------------------------
`expected_blocked_by` and `expected_slip_layers` on every AttackSample are
INDEPENDENT, A PRIORI design judgments about what a reasonably competent
defense SHOULD do with each attack, based on the attack's inherent
linguistic/structural properties — NOT labels derived by actually running
filtering.py / zedd.py / rag_memory.py against the sample and recording
what happened. Deriving the ground truth from the system under test would
make the evaluation circular: a layer would trivially "pass" evaluation
against labels generated by its own behavior. evaluator.py's entire job is
to run the REAL layers against these samples and measure how often the
REAL behavior matches these independently-authored expectations — that
comparison is the evaluation. This is the same approach used by benchmarks
like BIPIA (Yi et al., cited in the proposal): human-authored category
labels, checked empirically against real system behavior.

Two labels are more confidently known than others:
    - 'filtering' expectations are fairly confident because pattern-based
      matching is inherently predictable from the literal wording chosen.
    - 'zedd' / 'rag_memory' expectations are HYPOTHESES about semantic
      behavior — genuinely uncertain until validated against the real
      all-MiniLM-L6-v2 embeddings on your machine. Where a sample's
      designed intent specifically depends on embedding behavior we
      cannot verify from this sandbox, that uncertainty is noted in the
      attack_type or category docstring context, not hidden.

WHAT 'defensive_tokens' IN expected_slip_layers MEANS
----------------------------------------------------------
Layer 2 (defensive_tokens.py) never blocks anything by design — it only
transforms input. It is therefore listed in expected_slip_layers for
EVERY attack sample, structurally, not as a per-sample judgment call.
This is intentional and documented once here rather than repeated as a
comment on all 32 samples.

A STANDOUT CASE WORTH READING NOW: indirect_008 (false_data_injection)
---------------------------------------------------------------------------
This sample has expected_blocked_by=[] — none of the four content-analysis
layers are well-suited to catch it, because it contains no injected
LANGUAGE at all. It is a pure cross-sensor physical-consistency violation
(high load, flat temperature, static gas — see sensor_generator.py's
identical scenario). The only thing positioned to catch this is
grid_agent.py's OWN system-prompt instruction to reason about physical
consistency, which lives outside the defense stack entirely. This is an
intentional, important finding-in-waiting for the dissertation: the
defense-in-depth framework has a real gap for attacks that never touch
language, and human_loop.py is not guaranteed to help either, since
nothing here forces the agent's output to a HIGH-risk tool_call. Report
this honestly if evaluator.py confirms it, rather than treating it as an
implementation bug to quietly fix.
"""

from __future__ import annotations

